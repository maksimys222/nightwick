def svg(name, title, W, H, glass, anchor, zones):
    S = 16
    L, T = 34, 70
    label_x = L + W * S + 24
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{label_x + 600}" height="{T + H * S + 30}" font-family="Arial, sans-serif" font-size="10">',
         '<rect width="100%" height="100%" fill="#fff"/>',
         f'<text x="{L}" y="22" font-size="18" font-weight="bold">{title} — зоны ({W}×{H})</text>',
         f'<text x="{L}" y="40" font-size="12" fill="#555">Цветные прямоугольники — где должна быть каждая часть. Что внутри — придумываешь сам.</text>',
         f'<text x="{L}" y="56" font-size="12" fill="#555">Жёлтая линия — центр стекла (строка {glass}). Красная рамка — точка опоры (строка {anchor}, по центру).</text>']
    for y in range(H):
        for x in range(W):
            o.append(f'<rect x="{L + x * S}" y="{T + y * S}" width="{S}" height="{S}" fill="{"#f3f3f5" if (x + y) % 2 else "#fbfbfb"}"/>')
    # ось симметрии
    o.append(f'<line x1="{L + W * S / 2}" y1="{T}" x2="{L + W * S / 2}" y2="{T + H * S}" stroke="#aaa" stroke-dasharray="4 3"/>')
    for i, (nm, x0, x1, y0, y1, col, note) in enumerate(zones):
        X, Y, Wd, Hd = L + x0 * S, T + y0 * S, (x1 - x0 + 1) * S, (y1 - y0 + 1) * S
        o.append(f'<rect x="{X}" y="{Y}" width="{Wd}" height="{Hd}" fill="{col}" fill-opacity="0.55" stroke="{col}" stroke-width="2"/>')
        o.append(f'<text x="{X + Wd / 2}" y="{Y + Hd / 2 + 4}" text-anchor="middle" font-size="11" font-weight="bold">{nm.strip()}</text>')
        ly = T + (y0 + y1) / 2 * S + 4
        o.append(f'<line x1="{L + W * S + 2}" y1="{ly - 4}" x2="{label_x - 4}" y2="{ly - 4}" stroke="{col}"/>')
        o.append(f'<text x="{label_x}" y="{ly}" font-size="12"><tspan font-weight="bold">{nm.strip()}</tspan>: строки {y0}–{y1}, столбцы {x0}–{x1}'
                 + (f'<tspan fill="#666"> — {note}</tspan>' if note else '') + '</text>')
    for x in range(W + 1):
        o.append(f'<line x1="{L + x * S}" y1="{T}" x2="{L + x * S}" y2="{T + H * S}" stroke="{"#999" if x % 4 == 0 else "#ddd"}" stroke-width="{1 if x % 4 == 0 else 0.5}"/>')
    for y in range(H + 1):
        o.append(f'<line x1="{L}" y1="{T + y * S}" x2="{L + W * S}" y2="{T + y * S}" stroke="{"#999" if y % 4 == 0 else "#ddd"}" stroke-width="{1 if y % 4 == 0 else 0.5}"/>')
    for x in range(W):
        o.append(f'<text x="{L + x * S + S / 2}" y="{T - 4}" text-anchor="middle" fill="#666">{x}</text>')
    for y in range(H):
        o.append(f'<text x="{L - 4}" y="{T + y * S + S / 2 + 3.5}" text-anchor="end" fill="#666">{y}</text>')
    o.append(f'<rect x="{L}" y="{T + glass * S + S / 2 - 1.5}" width="{W * S}" height="3" fill="#e8b800"/>')
    o.append(f'<rect x="{L + (W // 2 - 1) * S}" y="{T + anchor * S}" width="{2 * S}" height="{S}" fill="none" stroke="#e00" stroke-width="3"/>')
    o.append('</svg>')
    open(os.path.join(OUT, name + '.svg'), 'w', encoding='utf-8').write('\n'.join(o))


for name, (title, W, H, glass, anchor, zones) in LAMPS.items():
    svg(name, title, W, H, glass, anchor, zones)
