# ---------- логотип: свой пиксельный шрифт ----------
# Заглавная Ф выше строчных на 3 строки; р и щ уходят вниз на 2 строки. Базовая линия — строка 10.
GLYPHS = {
    'Ф': ["....###....", ".#########.", "###.###.###", "##..###..##", "##..###..##", "##..###..##",
          "###.###.###", ".#########.", "....###....", "....###....", "....###...."],
    'о': [".#####.", "##...##", "##...##", "##...##", "##...##", "##...##", "##...##", ".#####."],
    'н': ["##...##", "##...##", "##...##", "#######", "#######", "##...##", "##...##", "##...##"],
    'а': [".#####.", "##...##", ".....##", ".######", "##...##", "##...##", "##..###", ".###.##"],
    'р': ["######.", "##...##", "##...##", "##...##", "##...##", "##...##", "######.", "##.....", "##.....", "##....."],
    'щ': ["##.##.##.", "##.##.##.", "##.##.##.", "##.##.##.", "##.##.##.", "##.##.##.", "##.##.##.",
          "#########", ".......##", "........#"],
    'и': ["##...##", "##...##", "##..###", "##.####", "####.##", "###..##", "##...##", "##...##"],
    'к': ["##...##", "##..##.", "##.##..", "####...", "####...", "##.##..", "##..##.", "##...##"],
}


def logo(text='Фонарщик'):
    pad, base = 3, 13           # базовая линия (низ строчных) — строка 13
    width = pad * 2 + sum(len(GLYPHS[c][0]) for c in text) + (len(text) - 1)
    G = Grid(width, base + 6)
    x = pad
    for c in text:
        rows = GLYPHS[c]
        top = base - 10 if c == 'Ф' else base - 7   # заглавная начинается выше
        for j, r in enumerate(rows):
            for i, ch in enumerate(r):
                if ch == '#':
                    y = top + j
                    # тёплый градиент сверху вниз: светлый — золотой — оранжевый
                    k = (y - (base - 10)) / 12
                    G.set(x + i, y, 'W' if k < 0.25 else ('Y' if k < 0.55 else ('y' if k < 0.8 else 'o')))
        x += len(rows[0]) + 1
    # тень вниз-вправо и тёмный контур
    shadow = [(x, y) for y in range(G.h) for x in range(G.w) if G.get(x, y) not in '.']
    for x, y in shadow:
        for dx, dy in ((1, 1), (0, 1), (1, 2)):
            if G.get(x + dx, y + dy) == '.': G.set(x + dx, y + dy, 'R')
    G.outline('K')
    # искорка над Ф
    for dx, dy, ch in ((0, -2, 'W'), (0, -1, 'Y'), (-1, -1, 'y'), (1, -1, 'y'), (0, 0, 'Y')):
        G.set(pad + 5 + dx, 2 + dy, ch)
    return G


if __name__ == '__main__':
    for name, rows in ICONS.items():
        G = Grid(16, 16)
        for y, r in enumerate(rows):
            assert len(r) == 16, (name, y, len(r))
            for x, ch in enumerate(r):
                if ch != '.': G.set(x, y, ch)
        save(OUT, 'icon_' + name, [G], PAL, preview=10)
    save(OUT, 'logo', [logo()], PAL, preview=6)
    print('ui ok')
