// ---------- заказы на доске ----------

export interface NightStats {
  lit: number[];
  harvested: number;
  maxBurning: number;
  lumens: number;
  found: ResidentId[];
  /** В каких районах этой ночью зажигали фонари. */
  districts: string[];
  /** Где этой ночью зажгли маяк (вылазка удалась). */
  beacon?: string;
}

export interface Quest {
  id: string;
  from: string;
  text: string;
  reward: number;
  /** Чей это заказ: появляется, когда житель переехал в мастерскую. */
  need: ResidentId | null;
  check: (n: NightStats, metCount: number) => boolean;
  final?: boolean;
}

